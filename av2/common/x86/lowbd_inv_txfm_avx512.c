// AVX-512 1D inverse transform kernels for bit depth 8.
//
// At bd == 8 the 2D driver clamps every value entering a 1D pass to int16
// range, so two taps can share one 32-bit lane and each pair of multiplies
// becomes a single vpmaddwd on packed int16 pairs.

// MSVC has no pragma to stop unrolling, and warns on unknown ones.
#if defined(__GNUC__)
#define NO_UNROLL _Pragma("GCC unroll 1")
#else
#define NO_UNROLL
#endif

// Packed tap-pair weights. vpmaddwd computes lo(a) * lo(b) + hi(a) * hi(b) in
// each 32-bit lane, so two taps feeding the same output need one instruction
// if their weights share a lane: tx_pair_<kernel>[p][k] is
// TX_PW(W[ta][k], W[tb][k]), where W is the INV_TXFM tx_kernel_* matrix and
// (ta, tb) is tap pair p. The DCT2 DC stages have no table: their weights are
// +/-64, which the kernels apply with an add or subtract and a shift.
//
// The tables below are generated by tools/gen_inv_txfm_pair_tables.py; do not
// edit them by hand.
#define TX_PW(lo, hi) \
  ((int32_t)(((uint32_t)(uint16_t)(hi) << 16) | (uint32_t)(uint16_t)(lo)))

