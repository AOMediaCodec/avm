// 8-bit 1D dispatcher. Mirrors inv_transform_1d_avx512: lengths 4/8 fall back
// to AVX2, and a length-32 axis only accepts DCT2 or IDTX.
void inv_transform_1d_lowbd_avx512(const int *src, int *dst, int shift,
                                   int line, int skip_line, int zero_line,
                                   int coef_min, int coef_max,
                                   int tx_type_index, int size_index) {
  if (size_index == 3) {
    if (tx_type_index == 0)
      inv_txfm_dct2_size32_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
    else if (tx_type_index == 1)
      inv_txfm_idtx_size32_avx512(src, dst, shift, line, skip_line, zero_line,
                                  coef_min, coef_max);
    else
      assert(0);
    return;
  }
  if (size_index != 2) {
    inv_transform_1d_avx2(src, dst, shift, line, skip_line, zero_line, coef_min,
                          coef_max, tx_type_index, size_index);
    return;
  }
  switch (tx_type_index) {
    case 0:
      inv_txfm_dct2_size16_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
      break;
    case 1:
      inv_txfm_idtx_size16_avx512(src, dst, shift, line, skip_line, zero_line,
                                  coef_min, coef_max);
      break;
    case 2:
      inv_txfm_adst_size16_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
      break;
    case 3:
      inv_txfm_fdst_size16_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
      break;
    case 4:
      inv_txfm_ddtx_size16_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
      break;
    case 5:
      inv_txfm_fddt_size16_lowbd_avx512(src, dst, shift, line, skip_line,
                                        zero_line, coef_min, coef_max);
      break;
    default: assert(0); break;
  }
}
